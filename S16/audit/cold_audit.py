    twice = {p: v for p, v in presented.items() if len(set(v)) > 1}
    check("AB01 coverage replay: every master page presented or disposed", not gaps and not extra,
          f"{len(presented)} pages presented by the edition PDFs, {len(disposed)} disposed, "
          f"{len(set(presented) & set(disposed))} both (blank pages printed in an edition and recorded as blank); "
          f"gaps {gaps[:10]}, out of range {extra[:10]}")
    prod = {int(r["master_pdf_page"]): r for r in rows(AB / "S16/integration/coverage_ab01.tsv")}
    disagree, blank_seen = [], []
