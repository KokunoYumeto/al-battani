def replay():
    tmp = Path(tempfile.mkdtemp(prefix="s16audit_"))
    report = []
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONDONTWRITEBYTECODE="1")
    for folder, builders, checkers, _ in REPLAY + table_replays():
        session = folder.split("/")[0]
        dest = tmp / session
        if not dest.exists():
            for p in git_files(session):
                q = dest / Path(p).relative_to(session)
                q.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(AB / p, q)
        work = dest / Path(folder).relative_to(session)
        committed = {p: sha(AB / p) for p in git_files(folder)}
        for p in committed:                          # the generated TeX must be regenerated, not left over
            if p.endswith(".tex") and (work / Path(p).relative_to(folder)).parent == work:
                (work / Path(p).relative_to(folder)).unlink()
        runs = []
        for b in builders:
            t0 = time.time()
            r = subprocess.run([sys.executable, b], cwd=work, env=env, capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=3600)
            runs.append((b, r.returncode, round(time.time() - t0, 1), (r.stdout + r.stderr).strip().splitlines()[-1:]))
        diff, missing = [], []
        for p, h in committed.items():
            q = work / Path(p).relative_to(folder)
            if not q.exists():
                missing.append(p)
            elif sha(q) != h:
                diff.append(p)
        made = sorted(p for p in committed if p.endswith(".tex") and (work / Path(p).relative_to(folder)).exists()
                      and (AB / p).parent == AB / folder)
        chk = []
        for c in checkers:
            r = subprocess.run([sys.executable, c], cwd=work, env=env, capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=3600)
            chk.append((c, r.returncode, (r.stdout + r.stderr).strip().splitlines()[-1:]))
        ok = all(x[1] == 0 for x in runs) and not diff and not missing and all(x[1] == 0 for x in chk)
        report.append({"folder": folder, "builders": runs, "tex_regenerated": made, "files_compared": len(committed),
                       "differ": diff, "missing_after_build": missing, "checks": chk, "pass": ok})
        print(("  ok   " if ok else "  FAIL ") + folder, runs, f"{len(diff)} differ", chk)
    shutil.rmtree(tmp, ignore_errors=True)
    (OUT / "replay_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n",
                                            encoding="utf-8", newline="\n")
    bad = [r["folder"] for r in report if not r["pass"]]
    check("session builds replayed byte-identical, session checks pass", not bad,
          f"{len(report)} folders replayed in temporary copies; " + (f"failed: {bad}" if bad else "all identical"))


