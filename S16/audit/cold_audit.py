def head_numbers(pdf):
    """the printed page number of each page from its running head: Western digits (Part II) or Arabic-Indic digits,
    extracted in visual order and so reversed (Part III)"""
    d = fitz.open(pdf)
    nums = []
    for p in d:
        h = p.rect.height
        words = [w for w in p.get_text("words") if w[1] < h * 0.09]
        if not words:
            nums.append((None, None))
            continue
        top = min(w[1] for w in words)
        line = sorted((w for w in words if w[1] < top + 6), key=lambda w: w[0])   # the topmost line only
        lat = [int(w[4]) for w in line if re.fullmatch(r"[0-9]{1,3}", w[4])]     # \d would take Arabic-Indic too
        ar = [int(w[4][::-1].translate(AR_DIGITS)) for w in line if re.fullmatch(r"[٠-٩]{1,3}", w[4])]
        nums.append(("II", lat[0]) if lat else ("III", ar[0]) if ar else (None, None))
    return nums


def blank_body(pdf, anchor):
    """the page of the edition that the bookmark of the anchor opens holds nothing but its running head, its page
    label, the anchor and the reader's page number"""
    d = fitz.open(pdf)
    pg = next((p for _, t, p in d.get_toc(simple=True) if t.startswith(anchor)), None)
    if pg is None:
        return False
    lines = [ln.strip() for ln in d[pg - 1].get_text().splitlines() if ln.strip()]
    rest = [ln for ln in lines if not (ln.isupper() or ln.startswith("PAG.") or ln == anchor or ln.isdigit())]
    return not rest


def declared_pages(folder):
    """the pages a table edition declares: S06 READMEs («Part II pp. ...»), S13 page ledgers, S13 figures and notice"""
    fam = folder.name
    if folder.parent.name == "S06":
        m = re.search(r"\[Part II pp?\. ([^\]]+?), \d+ pp?\.\]", (folder / "README.md").read_text(encoding="utf-8"))
        pages = []
        for a, b in re.findall(r"(\d+)(?:[–-](\d+))?", m.group(1)):
            pages += list(range(int(a), int(b or a) + 1))
        return {"p2_": [p + 449 for p in pages]}
    out = {}
    for f in sorted(folder.glob("*_p[23]_pages.tsv")) + sorted(folder.glob("p[23]_pages.tsv")):
        key = "p2_" if "p2_pages" in f.name or "_p2_" in f.name else "p3_"
        out.setdefault(key, [int(r["pdf"]) for r in rows(f)])
    if fam == "star_catalogue":            # its Part III page ledger lists only the signed pages
        out["p3_"] = sorted({int(r["pdf"]) for r in rows(folder / "p3_stars.tsv")}, reverse=True)
    if fam == "diagrams":
        out = {"p3_climates": [909], "p3_rosa": [908], "p2_climates": [541], "p2_rosa": [748]}
    if fam == "notice":
        out = {"p3_": [925]}
    return out


def coverage():
    presented = defaultdict(list)          # master page -> [pdf]
    notes = []
    for f in TOC_PDFS:
        d = fitz.open(AB / f)
        pages = [int(m.group(1)) for _, t, _ in d.get_toc(simple=True) for m in [re.match(r"AB01-PDF(\d{4})", t)] if m]
        for p in pages:
            presented[p].append(f)
        notes.append(f"{f}: {len(pages)} page bookmarks, {d.page_count} PDF pages")
    head_ok, head_missing, head_bad = 0, 0, []
    for folder in sorted((AB / "S06").iterdir()) + sorted((AB / "S13").iterdir()):
        if not folder.is_dir():
            continue
        decl = declared_pages(folder)
        for pdf in sorted(folder.glob("p[23]_*.pdf")):
            key = next((k for k in decl if pdf.stem.startswith(k)), None)
            if key is None:
                head_bad.append(f"{pdf.relative_to(AB).as_posix()}: no declared pages")
                continue
            want = decl[key]
            heads = head_numbers(pdf)
            if len(heads) != len(want):
                head_bad.append(f"{pdf.relative_to(AB).as_posix()}: {len(heads)} pages, {len(want)} declared")
            for (part, num), master in zip(heads, want):
                if num is None:
                    head_missing += 1
                else:
                    got = num + 449 if part == "II" else 1152 - num
                    if got == master:
                        head_ok += 1
                    else:
                        head_bad.append(f"{pdf.relative_to(AB).as_posix()}: head {num} -> PDF {got}, declared {master}")
                presented[master].append(pdf.relative_to(AB).as_posix())
    check("table editions: running heads agree with the declared pages", not head_bad,
          f"{head_ok} heads agree, {head_missing} pages have no number in the head (half-titles, figures, first "
          f"pages), {len(head_bad)} disagree" + (f": {head_bad[:6]}" if head_bad else ""))
    disposed = {}
    for r in rows(AB / "S01/ledgers/page_disposition.tsv"):
        if r["owned"] != "True" or r["kind"] == "intrinsic_blank_verso":
            disposed[int(r["master_pdf_page"])] = "S01: " + r["kind"]
